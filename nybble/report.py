def _fetch_sample(name: str, n: int) -> list[dict]:
    """Return up to *n* rows as a list of dicts."""
    con = session()
    with _SESSION_LOCK:
        try:
            _rel = con.sql(f'SELECT * FROM "{name}" LIMIT {n}').arrow()
            arrow = _rel.read_all() if hasattr(_rel, "read_all") else _rel
        except Exception:
            return []
    import polars as pl
    return pl.from_arrow(arrow).to_dicts()


def _md_escape(text: str) -> str:
    """Escape pipe characters so they don't break Markdown tables."""
    return text.replace("|", "\\|").replace("\n", " ").replace("\r", "")[:80]
