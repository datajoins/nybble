# ── Minimal Markdown → HTML converter (stdlib only) ──────────────────────────

def _md_to_html(md: str) -> str:
    """Convert a subset of Markdown to HTML using only the standard library.

    Handles: headings (h1-h4), fenced code blocks, blockquotes, horizontal
    rules, tables, bold/italic inline, inline code, paragraphs, and blank
    lines.  This is intentionally minimal - it covers only the constructs
    emitted by :func:`build_report`.
    """
    lines = md.splitlines()
    out: list[str] = []
    i = 0
    n = len(lines)

    while i < n:
        line = lines[i]

        # Fenced code block
        if line.strip().startswith("```"):
            lang = line.strip()[3:].strip()
            lang_attr = f' class="language-{_html_mod.escape(lang)}"' if lang else ""
            code_lines: list[str] = []
            i += 1
            while i < n and not lines[i].strip().startswith("```"):
                code_lines.append(_html_mod.escape(lines[i]))
                i += 1
            out.append(f"<pre><code{lang_attr}>" + "\n".join(code_lines) + "</code></pre>")
            i += 1
            continue

        # Horizontal rule
        if line.strip() in ("---", "***", "___"):
            out.append("<hr>")
            i += 1
            continue

        # Headings
        stripped = line.lstrip("#")
        level = len(line) - len(stripped)
        if 1 <= level <= 4 and (len(line) == level or line[level] == " "):
            text = _inline_md(stripped.strip())
            out.append(f"<h{level}>{text}</h{level}>")
            i += 1
            continue

        # Blockquote
        if line.startswith(">"):
            out.append(f"<blockquote>{_inline_md(line[1:].strip())}</blockquote>")
            i += 1
            continue

        # Markdown table: pipe-delimited lines
        if line.strip().startswith("|") and line.strip().endswith("|"):
            # Collect all consecutive table lines
            tbl_lines: list[str] = []
            while i < n and lines[i].strip().startswith("|") and lines[i].strip().endswith("|"):
                tbl_lines.append(lines[i])
                i += 1
            out.append(_md_table_to_html(tbl_lines))
            continue

        # Empty line → paragraph break
        if not line.strip():
            out.append("")
            i += 1
            continue

        # Paragraph / plain line
        out.append(f"<p>{_inline_md(line.strip())}</p>")
        i += 1

    return "\n".join(out)


def _inline_md(text: str) -> str:
    """Apply inline Markdown: bold, italic, inline code, and HTML-escape."""
    import re
    # HTML-escape first (before adding tags)
    text = _html_mod.escape(text)
    # Inline code  `...`
    text = re.sub(r"`([^`]+)`", r"<code>\1</code>", text)
    # Bold **...**
    text = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", text)
    # Italic *...*
    text = re.sub(r"\*(.+?)\*", r"<em>\1</em>", text)
    # Links [text](url)
    text = re.sub(r"\[([^\]]+)\]\(([^)]+)\)", r'<a href="\2">\1</a>', text)
    return text


def _md_table_to_html(rows: list[str]) -> str:
    """Convert pipe-delimited Markdown table rows to an HTML <table>."""
    parsed: list[list[str]] = []
    for row in rows:
        cells = [c.strip() for c in row.strip().strip("|").split("|")]
        parsed.append(cells)

    if not parsed:
        return ""

    html_parts = ["<table>", "<thead><tr>"]
    for cell in parsed[0]:
        html_parts.append(f"<th>{_inline_md(cell)}</th>")
    html_parts.append("</tr></thead>")

    if len(parsed) > 1:
        html_parts.append("<tbody>")
        # Skip the separator row (--- line)
        data_rows = [r for r in parsed[1:] if not all(
            set(c.replace(":", "").replace("-", "").strip()) <= {""} for c in r
        )]
        for row in data_rows:
            html_parts.append("<tr>")
            for cell in row:
                html_parts.append(f"<td>{_inline_md(cell)}</td>")
            html_parts.append("</tr>")
        html_parts.append("</tbody>")

    html_parts.append("</table>")
    return "\n".join(html_parts)


# ── New public API ────────────────────────────────────────────────────────────

def build_report(  # type: ignore[misc]  # overloaded below for legacy list path
    source: Union[str, Optional[list]],
    *,
    output: Union[str, Path] = "report.md",
    include_sample_rows: bool = True,
    sample_limit: int = 5,
    include_fk_queries: bool = True,
    include_schema: bool = True,
    # Legacy kwargs (ignored when source is a string path for KGResult path)
    include_profile: bool = False,
    sample_rows: int = 5,
) -> Union[NybbleReport, str]:
    """Build a Nybble report.

    **New API** - ``source`` is a string path to a data file or connection
    string.  Returns a :class:`NybbleReport`::

        report = build_report("mydb.sqlite")
        report.save("out.md")

    **Legacy API** - ``source`` is a list of relation names already loaded
    into the session.  Returns a Markdown string::

        load("data.csv", name="sales")
        md = build_report(["sales"])

    Parameters (new API)
    ----------
    source : str
        Path / connection string passed to :func:`nybble.kg.kg`.
    output : str | Path
        Default output path hint (used by the CLI; not written here).
    include_sample_rows : bool
        Include a sample-data section (default True).
    sample_limit : int
        Maximum rows per table in the sample section (default 5).
    include_fk_queries : bool
        Include auto-generated JOIN queries section (default True).
    include_schema : bool
        Include per-table schema section (default True).
    """
    # ── Legacy path: source is a list ────────────────────────────────────────
    if isinstance(source, list) or source is None:
        return _build_report_legacy(
            source,
            include_profile=include_profile,
            sample_rows=sample_rows,
        )

    # ── New path: source is a string (data path / connection string) ─────────
    return _build_report_from_source(
        source,
        include_sample_rows=include_sample_rows,
        sample_limit=sample_limit,
        include_fk_queries=include_fk_queries,
        include_schema=include_schema,
    )


def _build_report_from_source(
    source: str,
    *,
    include_sample_rows: bool = True,
    sample_limit: int = 5,
    include_fk_queries: bool = True,
    include_schema: bool = True,
) -> NybbleReport:
    """Internal implementation for the new-style build_report(source: str) path."""
    from nybble.kg import kg as _kg
    import networkx as nx

    # Obtain KGResult - this runs all inference pipelines exactly once.
    # kg() expects a list of relation names or paths; wrap the single source.
    result = _kg([source], open_browser=False)
    G: nx.MultiDiGraph = result.graph
    generated_at = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")

    # ── Derive tables and FK relationships from the graph ────────────────────
    # entity_type → {col: type} - built from graph nodes + DuckDB DESCRIBE fallback
    tables: dict[str, dict[str, str]] = {}  # table_name → {col: type}
    pk_cols: dict[str, str] = {}            # table_name → pk_col

    for _nid, attrs in G.nodes(data=True):
        tbl = attrs.get("entity_type", "")
        if not tbl:
            continue
        if tbl not in tables:
            tables[tbl] = {}
            pk_col = attrs.get("pk_col")
            if pk_col:
                pk_cols[tbl] = str(pk_col)
        # Capture column names from the row attribute
        row: dict = attrs.get("row", {})
        for col in row:
            if col not in tables[tbl]:
                tables[tbl][col] = type(row[col]).__name__

    # Fallback: ensure all registered relations are covered even if the graph
    # has no nodes (e.g., empty tables or large datasets trimmed by _build_graph).
    con = session()
    for rel_name in list(_REGISTERED.keys()):
        if rel_name not in tables:
            with _SESSION_LOCK:
                try:
                    schema_rows = con.execute(
                        f'DESCRIBE SELECT * FROM "{rel_name}" LIMIT 0'
                    ).fetchall()
                except Exception:
                    schema_rows = []
            if schema_rows:
                tables[rel_name] = {r[0]: r[1] for r in schema_rows}

    # FK relationships - extract from graph edges (FK: prefix) and supplement
    # with infer_fks() on registered relations so that candidates with no
    # matching row values are still captured in the report.
    from nybble.infer_fk import infer_fks as _infer_fks

    fk_edges: list[tuple[str, str, str, str, float]] = []  # (src_t, src_c, tgt_t, tgt_c, conf)
    seen_fk: set[tuple[str, str, str, str]] = set()

    # First: from graph edges
    for _src, _tgt, attrs in G.edges(data=True):
        rel_attr = attrs.get("relation", "")
        if not rel_attr.startswith("FK:"):
            continue
        # FK:src_table.src_col→tgt_table.tgt_col
        payload = rel_attr[3:]
        if "→" in payload and "." in payload:
            left, right = payload.split("→", 1)
            if "." in left and "." in right:
                src_t, src_c = left.rsplit(".", 1)
                tgt_t, tgt_c = right.rsplit(".", 1)
                key = (src_t, src_c, tgt_t, tgt_c)
                if key not in seen_fk:
                    seen_fk.add(key)
                    conf = float(attrs.get("confidence", 1.0))
                    fk_edges.append((src_t, src_c, tgt_t, tgt_c, conf))

    # Second: infer_fks() on registered relations (catches FKs with no row matches)
    rels = list(_REGISTERED.values())
    for fk in _infer_fks(rels):
        key = (fk.src_table, fk.src_col, fk.tgt_table, fk.tgt_col)
        if key not in seen_fk:
            seen_fk.add(key)
            fk_edges.append((fk.src_table, fk.src_col, fk.tgt_table, fk.tgt_col, fk.confidence))

    sections: list[ReportSection] = []

    # ── Section 1: Overview ──────────────────────────────────────────────────
    overview_lines = [
        f"| Field | Value |",
        f"|-------|-------|",
        f"| Source | `{source}` |",
        f"| Tables | {len(tables)} |",
        f"| FK Relationships | {len(fk_edges)} |",
        f"| Generated | {generated_at} |",
    ]
    sections.append(ReportSection(title="Overview", content="\n".join(overview_lines) + "\n"))

    # ── Section 2: Schema Tables ─────────────────────────────────────────────
    if include_schema:
        schema_parts: list[str] = []
        fk_src_map: dict[str, set[str]] = {}  # table → FK src cols
        fk_tgt_map: dict[str, set[str]] = {}  # table → FK tgt cols (PK side)
        for src_t, src_c, tgt_t, tgt_c, _ in fk_edges:
            fk_src_map.setdefault(src_t, set()).add(src_c)
            fk_tgt_map.setdefault(tgt_t, set()).add(tgt_c)

        for tbl, cols in sorted(tables.items()):
            schema_parts.append(f"### `{tbl}`\n")
            schema_parts.append("| Column | Type | Key |")
            schema_parts.append("|--------|------|-----|")
            pk_col = pk_cols.get(tbl)
            for col, col_type in cols.items():
                key_ann = ""
                if col == pk_col:
                    key_ann = "PK"
                elif col in fk_src_map.get(tbl, set()):
                    key_ann = "FK"
                elif col in fk_tgt_map.get(tbl, set()):
                    key_ann = "PK/FK target"
                schema_parts.append(f"| `{col}` | `{col_type}` | {key_ann} |")
            schema_parts.append("")
        sections.append(ReportSection(title="Schema Tables", content="\n".join(schema_parts)))

    # ── Section 3: Foreign Key Summary ───────────────────────────────────────
    fk_lines = [
        "| From Table | From Column | To Table | To Column | Confidence |",
        "|------------|-------------|----------|-----------|------------|",
    ]
    for src_t, src_c, tgt_t, tgt_c, conf in fk_edges:
        fk_lines.append(
            f"| `{src_t}` | `{src_c}` | `{tgt_t}` | `{tgt_c}` | {conf:.0%} |"
        )
    sections.append(ReportSection(
        title="Foreign Key Summary",
        content="\n".join(fk_lines) + "\n",
    ))

    # ── Section 4: Sample Data ───────────────────────────────────────────────
    if include_sample_rows:
        sample_parts: list[str] = []
        con = session()
        for tbl in sorted(tables.keys()):
            sample_parts.append(f"### `{tbl}`\n")
            with _SESSION_LOCK:
                try:
                    rows_raw = con.execute(
                        f'SELECT * FROM "{tbl}" LIMIT {sample_limit}'
                    ).fetchall()
                    col_names = [
                        desc[0] for desc in con.execute(
                            f'DESCRIBE SELECT * FROM "{tbl}" LIMIT 0'
                        ).fetchall()
                    ]
                    if rows_raw and col_names:
                        sample_parts.append("| " + " | ".join(f"`{c}`" for c in col_names) + " |")
                        sample_parts.append("| " + " | ".join("---" for _ in col_names) + " |")
                        for row in rows_raw:
                            cells = [_md_escape(str(v) if v is not None else "NULL") for v in row]
                            sample_parts.append("| " + " | ".join(cells) + " |")
                    else:
                        sample_parts.append("_No rows._")
                except Exception as exc:
                    sample_parts.append(f"```\nError fetching sample: {exc}\n```")
            sample_parts.append("")
        sections.append(ReportSection(title="Sample Data", content="\n".join(sample_parts)))

    # ── Section 5: Key Queries ───────────────────────────────────────────────
    if include_fk_queries:
        query_parts: list[str] = []
        for src_t, src_c, tgt_t, tgt_c, _ in fk_edges:
            sql = textwrap.dedent(f"""\
                SELECT
                  a.*,
                  b.*
                FROM "{src_t}" a
                INNER JOIN "{tgt_t}" b
                  ON a."{src_c}" = b."{tgt_c}"
                LIMIT 20;""")
            query_parts += [
                f"### `{src_t}` ↔ `{tgt_t}`\n",
                "```sql",
                sql,
                "```",
                "",
            ]
        if not query_parts:
            query_parts.append("_No FK relationships detected - no JOIN queries generated._\n")
        sections.append(ReportSection(title="Key Queries", content="\n".join(query_parts)))

    return NybbleReport(
        source=source,
        generated_at=generated_at,
        sections=sections,
    )


# ── Legacy API (backward compatible) ─────────────────────────────────────────

def _build_report_legacy(
    relations: Optional[list] = None,
    *,
    include_profile: bool = False,
    sample_rows: int = 5,
) -> str:
    """Generate a Markdown report for all (or specified) loaded relations.

    Parameters
    ----------
    relations:
        Relation objects or table names to include.  Defaults to all registered.
    include_profile:
        When True, include a column-profiling section with null%, distinct,
        min and max values.  This adds one DuckDB query per table.
    sample_rows:
        Number of sample rows to include per table (0 to skip).

    Returns
    -------
    str
        Complete Markdown document.
    """
    from nybble.infer_fk import infer_fks

    # Resolve relations
    if relations is None:
        rels = list(_REGISTERED.values())
    else:
        rels = []
        for r in relations:
            if isinstance(r, str):
                rels.append(_REGISTERED[r] if r in _REGISTERED
                            else __import__("nybble").load(r))
            else:
                rels.append(r)

    if not rels:
        return "# Nybble Report\n\n_No data sources loaded._\n"

    fk_candidates = infer_fks(rels)
    ts = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    total_rows = sum(r.row_count or 0 for r in rels)

    lines: list[str] = []

    # ── Header ────────────────────────────────────────────────────────────────
    lines += [
        "# Nybble Data Report",
        "",
        f"> Generated: {ts}",
        "",
        "## Workspace Summary",
        "",
        "| Metric | Value |",
        "|--------|-------|",
        f"| Sources | {len(rels)} |",
        f"| Total rows | {total_rows:,} |",
        f"| Inferred FK relationships | {len(fk_candidates)} |",
        "",
    ]

    # ── Per-table sections ────────────────────────────────────────────────────
    lines.append("## Tables")
    lines.append("")

    for rel in rels:
        schema = rel.schema()
        row_count = rel.row_count or 0

        # FK annotations
        pk_cols_set = {fk.tgt_col for fk in fk_candidates if fk.tgt_table == rel.name}
        fk_col_map = {fk.src_col: fk for fk in fk_candidates if fk.src_table == rel.name}

        lines += [
            f"### `{rel.name}`",
            "",
            f"- **Source:** `{rel.source}`",
            f"- **Type:** {rel.source_type}",
            f"- **Rows:** {row_count:,}",
            "",
            "#### Schema",
            "",
            "| Column | Type | Key |",
            "|--------|------|-----|",
        ]

        for col in schema:
            n, t = col["name"], col["type"]
            key = ""
            if n in pk_cols_set:
                key = "🔑 PK"
            elif n in fk_col_map:
                fk = fk_col_map[n]
                key = f"🔗 FK → `{fk.tgt_table}.{fk.tgt_col}` (tier {fk.tier}, {fk.confidence:.0%})"
            lines.append(f"| `{n}` | `{t}` | {key} |")

        lines.append("")

        # Column profiling
        if include_profile:
            from nybble.profiler import profile_relation
            profiles = profile_relation(rel.name)
            if profiles:
                lines += [
                    "#### Column Profile",
                    "",
                    "| Column | Non-null% | Distinct | Card% | Min | Max | Top value |",
                    "|--------|-----------|----------|-------|-----|-----|-----------|",
                ]
                for p in profiles:
                    approx = "~" if p.approx else ""
                    lines.append(
                        f"| `{p.name}` "
                        f"| {100 - p.null_pct:.1f}% "
                        f"| {approx}{p.distinct:,} "
                        f"| {p.cardinality_pct:.1f}% "
                        f"| {_md_escape(p.min_val or '-')} "
                        f"| {_md_escape(p.max_val or '-')} "
                        f"| {_md_escape(p.top_val or '-')} |"
                    )
                lines.append("")

        # Sample rows
        if sample_rows > 0 and row_count > 0:
            sample = _fetch_sample(rel.name, sample_rows)
            if sample:
                col_names = list(sample[0].keys())
                lines += [
                    f"#### Sample Rows (up to {sample_rows})",
                    "",
                    "| " + " | ".join(f"`{c}`" for c in col_names) + " |",
                    "| " + " | ".join("---" for _ in col_names) + " |",
                ]
                for row in sample:
                    cells = [_md_escape(str(row.get(c, "")) or "NULL") for c in col_names]
                    lines.append("| " + " | ".join(cells) + " |")
                lines.append("")

    # ── FK relationship summary ───────────────────────────────────────────────
    if fk_candidates:
        lines += [
            "## Inferred Relationships",
            "",
            "| From | Column | To | Column | Tier | Confidence |",
            "|------|--------|-----|--------|------|------------|",
        ]
        for fk in fk_candidates:
            lines.append(
                f"| `{fk.src_table}` | `{fk.src_col}` "
                f"| `{fk.tgt_table}` | `{fk.tgt_col}` "
                f"| {fk.tier} | {fk.confidence:.0%} |"
            )
        lines.append("")

        # Auto-generated JOIN queries
        lines += [
            "## Generated JOIN Queries",
            "",
            "_Copy-paste these queries into `nybble repl` or the query panel._",
            "",
        ]
        seen_pairs: set[tuple[str, str]] = set()
        for fk in fk_candidates:
            pair = (fk.src_table, fk.tgt_table)
            if pair in seen_pairs:
                continue
            seen_pairs.add(pair)
            sql = (
                f"SELECT\n"
                f"  a.*,\n"
                f"  b.*\n"
                f"FROM \"{fk.src_table}\" a\n"
                f"JOIN \"{fk.tgt_table}\" b\n"
                f"  ON a.\"{fk.src_col}\" = b.\"{fk.tgt_col}\"\n"
                f"LIMIT 100;"
            )
            lines += [
                f"### `{fk.src_table}` ↔ `{fk.tgt_table}`",
                "",
                "```sql",
                sql,
                "```",
                "",
            ]

    # ── Footer ────────────────────────────────────────────────────────────────
    lines += [
        "---",
        "",
        "_Report generated by [Nybble](https://github.com/datajoins/nybble) "
        "- ultra-lightweight data engine._",
        "",
    ]

    return "\n".join(lines)


def save_report(
    path: Union[str, Path],
    relations: Optional[list] = None,
    *,
    include_profile: bool = False,
    sample_rows: int = 5,
) -> Path:
    """Write the legacy Markdown report to *path* and return the resolved Path."""
    out = Path(path)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        _build_report_legacy(
            relations,
            include_profile=include_profile,
            sample_rows=sample_rows,
        ),
        encoding="utf-8",
    )
    return out


