"""
report.py - Markdown Data Report Builder

Generates a structured Markdown document from all loaded relations containing:
  1. Overview (source path, table count, relationship count, timestamp)
  2. Schema Tables - per-table column details with PK/FK annotations
  3. Foreign Key Summary - every inferred FK with confidence score
  4. Sample Data - up to N rows per table
  5. Key Queries - auto-generated INNER JOIN SQL per FK relationship

Also supports the legacy build_report(relations, ...) → str API for
backward compatibility with existing callers.

Public API
----------
  build_report(source, *, output, include_sample_rows, sample_limit,
               include_fk_queries, include_schema) → NybbleReport
  build_report(relations, *, include_profile, sample_rows) → str   # legacy
  save_report(path, relations, **kwargs) → Path                     # legacy
"""
from __future__ import annotations

import html as _html_mod
import textwrap
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import List, Optional, Union

from nybble.resolver import Relation, _REGISTERED, session, _SESSION_LOCK


# ── Data model ────────────────────────────────────────────────────────────────

@dataclass
class ReportSection:
    """A single titled section of a :class:`NybbleReport`."""

    title: str
    content: str  # Markdown-formatted string


@dataclass
class NybbleReport:
    """Structured report produced by :func:`build_report`.

    Attributes
    ----------
    source       : str - the source path / identifier passed to build_report
    generated_at : str - ISO 8601 UTC timestamp
    sections     : list[ReportSection]
    """

    source: str
    generated_at: str
    sections: List[ReportSection]

    # ── Rendering ─────────────────────────────────────────────────────────────

    def to_markdown(self) -> str:
        """Render the report as a Markdown string."""
        parts: list[str] = [f"# Nybble Report\n", f"> Generated: {self.generated_at}\n"]
        for sec in self.sections:
            parts.append(f"\n## {sec.title}\n")
            parts.append(sec.content)
        parts.append(
            "\n---\n\n_Report generated by "
            "[Nybble](https://github.com/datajoins/nybble) "
            "- ultra-lightweight data engine._\n"
        )
        return "\n".join(parts)

    def to_html(self) -> str:
        """Render the report as a self-contained HTML document."""
        md = self.to_markdown()
        body_html = _md_to_html(md)
        return _HTML_SHELL.format(
            title=_html_mod.escape(f"Nybble Report - {self.source}"),
            body=body_html,
        )

    def save(self, path: Union[str, Path]) -> Path:
        """Write the report to *path* (.md or .html) and return the resolved Path."""
        out = Path(path)
        out.parent.mkdir(parents=True, exist_ok=True)
        if out.suffix.lower() == ".html":
            out.write_text(self.to_html(), encoding="utf-8")
        else:
            out.write_text(self.to_markdown(), encoding="utf-8")
        return out


