"""ERD renderer.

Converts a normalized Schema object into:
  1. A PostgreSQL-dialect DDL file (schema.sql) that Liam can parse.
  2. An interactive HTML ERD via @liam-hq/cli.

This module has zero knowledge of the original input format.
It consumes only the schema_model.Schema dataclass.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

from server.ingestion.schema_model import Column, ForeignKey, Index, Schema, Table


# ---------------------------------------------------------------------------
# DDL generation  (PostgreSQL dialect - accepted by Liam --format postgres)
# ---------------------------------------------------------------------------

def _col_ddl(col: Column, is_last: bool) -> str:
    parts = [f"    {_quote(col.name)}", _pg_type(col.data_type)]
    if col.primary_key:
        parts.append("PRIMARY KEY")
    if not col.nullable and not col.primary_key:
        parts.append("NOT NULL")
    if col.unique and not col.primary_key:
        parts.append("UNIQUE")
    if col.default is not None and col.default not in ("AUTO_INCREMENT", "nextval"):
        parts.append(f"DEFAULT {col.default}")
    line = " ".join(parts)
    return line if is_last else line + ","


def _fk_ddl(fk: ForeignKey) -> str:
    src = ", ".join(_quote(c) for c in fk.constrained_columns)
    ref = ", ".join(_quote(c) for c in fk.referred_columns)
    return (
        f"    FOREIGN KEY ({src}) "
        f"REFERENCES {_quote(fk.referred_table)} ({ref})"
    )


def _table_ddl(table: Table) -> str:
    lines = [f"CREATE TABLE {_quote(table.name)} ("]
    all_clauses: list[str] = []

    # Columns
    for col in table.columns:
        all_clauses.append(_col_ddl(col, is_last=False))

    # Multi-column PK (only when not already set inline)
    multi_pk = [pk for pk in table.primary_keys
                if sum(1 for c in table.columns if c.primary_key) == 0]
    if multi_pk:
        pk_cols = ", ".join(_quote(c) for c in multi_pk)
        all_clauses.append(f"    PRIMARY KEY ({pk_cols}),")

    # Foreign keys
    for fk in table.foreign_keys:
        all_clauses.append(_fk_ddl(fk) + ",")

    # Fix trailing comma on last clause
    if all_clauses:
        all_clauses[-1] = all_clauses[-1].rstrip(",")

    lines.extend(all_clauses)
    lines.append(");")

    # COMMENT ON TABLE
    lines.append(f"COMMENT ON TABLE {_quote(table.name)} IS "
                 f"'{table.name} ({len(table.columns)} columns)';")

    # Stand-alone indexes
    for idx in table.indexes:
        unique_kw = "UNIQUE " if idx.unique else ""
        idx_cols = ", ".join(_quote(c) for c in idx.columns)
        lines.append(
            f"CREATE {unique_kw}INDEX {_quote(idx.name)} "
            f"ON {_quote(table.name)} ({idx_cols});"
        )

    return "\n".join(lines)


def schema_to_ddl(schema: Schema) -> str:
    """Convert a Schema to a full PostgreSQL DDL string for Liam."""
    header = [
        "-- ============================================================",
        f"--  Schema: {schema.name}",
        f"--  Tables: {len(schema.tables)}",
        f"--  Auto-generated by generate_erd.py",
        "-- ============================================================",
        "",
    ]
    table_blocks = [_table_ddl(t) for t in schema.tables]
    return "\n".join(header) + "\n\n".join(table_blocks)


def _pg_type(raw: str) -> str:
    """Map any raw type string to a PostgreSQL-compatible type.

    Liam only needs something recognizable - precision / length details
    are fine to keep as-is.
    """
    upper = raw.upper()
    # MySQL-specific aliases that are not valid PG keywords
    aliases = {
        "TINYINT":    "SMALLINT",
        "MEDIUMINT":  "INTEGER",
        "INT":        "INTEGER",
        "DOUBLE":     "DOUBLE PRECISION",
        "FLOAT":      "REAL",
        "MEDIUMTEXT": "TEXT",
        "LONGTEXT":   "TEXT",
        "TINYTEXT":   "TEXT",
        "DATETIME":   "TIMESTAMP",
        "ENUM":       "TEXT",
        "SET":        "TEXT",
    }
    # Strip parenthesised size for comparison
    base = upper.split("(")[0].strip()
    return aliases.get(base, raw)


def _quote(name: str) -> str:
    return f'"{name}"'


# ---------------------------------------------------------------------------
# Liam invocation
# ---------------------------------------------------------------------------

def _liam_cli_cmd(schema_path: Path, output_dir: Path) -> list:
    """Build the command list for @liam-hq/cli erd build.

    Prefers the locally built fork at LIAM_CLI_DIR (set by Dockerfile).
    Falls back to npx @liam-hq/cli@latest when the env var is absent.
    """
    import os
    liam_cli_dir = os.environ.get("LIAM_CLI_DIR", "").strip()
    if liam_cli_dir:
        # LIAM_CLI_DIR points to the entire cli package directory
        # The binary is at dist-cli/bin/cli.js, cwd must be the package dir
        # so Node can resolve node_modules via normal module resolution.
        cli_bin = str(Path(liam_cli_dir) / "dist-cli" / "bin" / "cli.js")
        return [
            "node", cli_bin,
            "erd", "build",
            "--input",      str(schema_path),
            "--format",     "postgres",
            "--output-dir", str(output_dir),
        ]
    # Fallback: use the published package via npx
    return [
        "npx", "--yes", "@liam-hq/cli@latest",
        "erd", "build",
        "--input",      str(schema_path),
        "--format",     "postgres",
        "--output-dir", str(output_dir),
    ]


def render(schema: Schema, output_dir: str | Path) -> Path:
    """Write schema.sql and run @liam-hq/cli to produce the ERD HTML.

    Returns the path to the generated index.html.
    """
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    schema_path = output_dir / "schema.sql"
    ddl = schema_to_ddl(schema)
    schema_path.write_text(ddl, encoding="utf-8")
    print(f"[ok] DDL written -> {schema_path}  ({len(schema.tables)} tables)")

    print("[..] Running @liam-hq/cli erd build ...")
    cmd = _liam_cli_cmd(schema_path, output_dir)
    # When using the local CLI, run from the CLI package directory so that
    # Node's module resolution can find node_modules/
    import os
    liam_cli_dir = os.environ.get("LIAM_CLI_DIR", "").strip()
    cwd = liam_cli_dir if liam_cli_dir else None
    result = subprocess.run(
        cmd,
        cwd=cwd,
        shell=(sys.platform == "win32"),
        capture_output=False,
        text=True,
    )
    if result.returncode != 0:
        print("[!!] liam-hq/cli exited with a non-zero status.", file=sys.stderr)
        sys.exit(result.returncode)

    index = output_dir / "index.html"
    if not index.exists():
        candidates = list(output_dir.rglob("index.html"))
        index = candidates[0] if candidates else output_dir / "index.html"

    print(f"[ok] ERD ready -> {index}")
    return index
